/*!****************************************************************************
 *  @file       rsa_2048_pss_sha256_fast_verify.c
 *  @brief      RSA-2048 PSS signature fast verify basic example
 *
 *  This code example demonstrates how to use the RSA fast verify function pair
 *  with a 2048-bit modulus and the PSS padding scheme from RFC 8017.
 *
 *  Compared with the standard (non-fast) RSA verify example, this example
 *  separates the preparation of the RSA public key parameters from the actual
 *  message specific verification.  This allows a speed-up in the case where
 *  the public key is known in advance (this is usually the case) or when
 *  multiple verifies are to be done on the same public key.
 *
 *  This example uses SHA-256 for the message pre-hash as well
 *  as the PSS MGF hash function.
 *
 *  The routine is expected to return a VALID status.
 *  To test the INVALID signature case, change  any part of the message
 *  and re-run the example to confirm that INVALID is reported.
 *
 ******************************************************************************
 */

