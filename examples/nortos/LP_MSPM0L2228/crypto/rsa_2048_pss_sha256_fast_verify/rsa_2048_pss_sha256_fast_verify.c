/* SRAM buffer to store the SHA-256 message digest (32 bytes / 8 words) */
static uint32_t md[MD_LEN];

int main(void)
{
    crypto_rsa_fast_verify_pk_t pk;
    crypto_hash_stat_t hashStat;
    crypto_rsa_stat_t rsaStat;

    SYSCFG_DL_init();

    /* Before verifying a message, we prepare the public key data structure in advance.
     * This data structure stores the additional RSA public key parameters which are used
     * during the verification process.  Pre-computing these values reduces the
     * verify compute time later during message verification.
     */
    rsaStat = Crypto_RSA_preparePkFromModulus(rsa_modulus_be,
                                              sizeof(rsa_modulus_be),
                                              CRYPTO_RSA_BIG_ENDIAN,
                                              &pk);

    /* If the operation was not successful, jump to error trap */
    if (rsaStat != CRYPTO_RSA_STAT_OK) {
        goto err;
    }

    /* Now, let's compute the message SHA-256 hash digest */
    hashStat = Crypto_SHA256(test_message, sizeof(test_message), md);

    /* If the operation was not successful, jump to error trap */
    if (hashStat != CRYPTO_HASH_STAT_OK) {
        goto err;
    }

    /* Run the verify operation */
    rsaStat = Crypto_RSA_PSS_fastVerify(&pk,
                                        (uint8_t*)(&md[0]),
                                        CRYPTO_RSA_MD_SHA256,
                                        rsa_pss_signature,
                                        sizeof(rsa_pss_signature),
                                        SALT_LEN);

    /* If the operation was not successful, jump to error trap */
    if (rsaStat != CRYPTO_RSA_STAT_VALID_SIGNATURE) {
        goto err;
    }

    /* Trap here on a pass condition */
    while (1) {
        __NOP();
    }

err:
    /* Trap here on an error condition */
    while (1) {
        __NOP();
    }
}
